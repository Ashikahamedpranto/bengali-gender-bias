count = 0
with open("bengali_newspaper_corpus.txt", "w", encoding="utf-8") as f_out:
    for filepath in csv_files:
        try:
            df = pd.read_csv(filepath)
            for _, row in df.iterrows():
                if row.get('status') == 'published':
                    body = clean_newspaper_text(row.get('body'))
                    if len(body) > 20:
                        f_out.write(body + "\n")
                        count += 1
        except Exception as e:
            print(f"Error in {filepath}: {e}")

print(f"\nTotal articles written: {count}")

