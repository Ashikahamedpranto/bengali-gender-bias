def cosine_sim(vec1, vec2):
    return np.dot(vec1, vec2) / (np.linalg.norm(vec1) * np.linalg.norm(vec2))
def multiword_vector(phrase_words, model):
    vecs = [model.wv[w] for w in phrase_words if w in model.wv]
    if not vecs:
        return None
    return np.mean(vecs, axis=0)
def direct_bias_vec(vec, gender_direction, c=1):
    cos_sim = cosine_sim(vec, gender_direction)
    return abs(cos_sim) ** c * np.sign(cos_sim)

def count_phrase_streaming(filepath, phrase):
    count = 0
    with open(filepath, encoding="utf-8") as f:
        for line in f:
            count += line.count(phrase)
    return count

