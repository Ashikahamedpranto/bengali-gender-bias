"""**Now let's move to the actual bias calculation — this is the core of the whole methodology.**

*Step 1: Build the Gender Direction from our 7 defining pairs*

This code takes our 7 defining word pairs (woman-man, daughter-son, etc.) and calculates the vector difference for each pair — essentially "female word minus male word". For each pair, it checks that both words actually exist in our trained Word2Vec model, calculates the difference (female vector − male vector), and collects all these differences into a list. At the end, it tells you how many of the 7 pairs were successfully processed (ideally all 7, but it'll flag and skip any pair where one of the words wasn't found in the vocabulary). These 7 (or however many succeed) difference vectors are the raw ingredients that the next step (PCA) will use to calculate the overall "gender direction" — the mathematical compass that every profession word will later be compared against.

***this step is purely about calculating those 7 individual differences***
"""

