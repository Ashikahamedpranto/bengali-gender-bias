"""Run the filmmaker/comedian block now:

Filmmaker and comedian in Bengali are two-word phrases (like "film-maker"), so Word2Vec never learned a single vector for the whole phrase — only for each individual word separately. To work around this, we averaged the vectors of the component words together (e.g., চলচ্চিত্র + নির্মাতা) to create an approximate combined vector for the whole phrase, then ran the same bias calculation on that averaged vector as we did for every other word. For comedian specifically, since it also has separate male and female forms, we did this component-averaging twice (once for the male phrase, once for the female phrase), then combined those two results using the same frequency-weighted averaging method used earlier for teacher/actor/writer — giving one final bias score for comedian overall.
"""

def multiword_vector(phrase_words, model):
    vecs = [model.wv[w] for w in phrase_words if w in model.wv]
    if not vecs:
        return None
    return np.mean(vecs, axis=0)

