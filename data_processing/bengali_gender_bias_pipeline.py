"""Here we calculated the actual DirectBias scores for all our profession words, following Formula 1 from the paper.

Step 3: DirectBias calculation

this entire step is specifically about figuring out, for each of our 32 profession words, whether the word's real-world usage pattern in Bengali Wikipedia leans toward representing "male" or "female" concepts — and by how much. That's the whole point of the DirectBias calculation, and it's the final, actual output our whole project has been building toward.
"""

import numpy as np

def cosine_sim(vec1, vec2):
    return np.dot(vec1, vec2) / (np.linalg.norm(vec1) * np.linalg.norm(vec2))

def direct_bias(word, gender_direction, model, c=1):
    if word not in model.wv:
        return None
    vec = model.wv[word]
    cos_sim = cosine_sim(vec, gender_direction)
    return abs(cos_sim) ** c * np.sign(cos_sim)  # keep sign to show direction (F/M)

